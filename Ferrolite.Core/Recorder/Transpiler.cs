using System.Globalization;
using System.Text;

namespace Ferrolite.Core.Recorder;









public static class Transpiler
{
    private const double ShortHoldThreshold = 0.35;
    private const double TypingGapThreshold = 1.0;

    
    private abstract class TlEvent { public double SortKey; }
    private class MoveEv : TlEvent { public int X, Y; }
    private class MoveRelEv : TlEvent { public double Dx, Dy; }
    private class ScrollEv : TlEvent { public int? X, Y; public int Dy; }
    private class Span : TlEvent { public double End; }
    private class KeySpan : Span { public string Key = ""; }
    private class MouseSpan : Span { public string Button = ""; public int? X, Y; }

    public static string Transpile(List<RecordedEvent> events, bool loop = false, int? loopCount = null,
        bool collapseTyping = false, double minWaitThreshold = 0.002, bool correctRelativeDrift = true)
    {
        
        
        var prevCulture = CultureInfo.CurrentCulture;
        CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
        try
        {
            return TranspileCore(events, loop, loopCount, collapseTyping, minWaitThreshold, correctRelativeDrift);
        }
        finally
        {
            CultureInfo.CurrentCulture = prevCulture;
        }
    }

    private static string TranspileCore(List<RecordedEvent> events, bool loop, int? loopCount,
        bool collapseTyping, double minWaitThreshold, bool correctRelativeDrift)
    {
        var included = events.Where(e => e.Included).ToList();
        if (included.Count == 0) return "# No events recorded.\n";

        var timeline = BuildTimeline(included);
        var bodyLines = RenderTimeline(timeline, collapseTyping, minWaitThreshold);
        var header = new List<string>
        {
            "# Auto-generated by Ferrolite Recorder",
            "# Edit freely -- this is normal Ferrolite source.",
            "",
        };

        if (!loop)
            return string.Join("\n", header.Concat(bodyLines).Concat(new[] { "" }));

        
        if (correctRelativeDrift)
        {
            double netDx = included.Where(e => e.Type == EventType.MouseMoveRelative).Sum(e => e.Dx ?? 0);
            double netDy = included.Where(e => e.Type == EventType.MouseMoveRelative).Sum(e => e.Dy ?? 0);
            if (netDx != 0 || netDy != 0)
            {
                bodyLines.AddRange(new[]
                {
                    "# Drift correction: undo this recording's net relative",
                    "# displacement so looping repeats the same motion instead",
                    "# of drifting further in the same direction each time.",
                    $"move_relative({Math.Round(-netDx, 2)}, {Math.Round(-netDy, 2)})",
                });
            }
        }

        var indented = bodyLines.Select(l => l.Trim().Length == 0 ? l : "    " + l).ToList();
        string loopOpen = loopCount is null ? "while true {" : $"for _rep in range({loopCount.Value}) {{";
        return string.Join("\n", header.Concat(new[] { loopOpen }).Concat(indented).Concat(new[] { "}", "" }));
    }

    private static List<TlEvent> BuildTimeline(List<RecordedEvent> events)
    {
        var timeline = new List<TlEvent>();
        var openHolds = new Dictionary<string, List<double>>();       
        var openMouseHolds = new Dictionary<string, List<(double ts, int? x, int? y)>>();

        void PushHeld<T>(Dictionary<string, List<T>> d, string k, T v)
        {
            if (!d.TryGetValue(k, out var l)) { l = new List<T>(); d[k] = l; }
            l.Add(v);
        }

        foreach (var ev in events)
        {
            switch (ev.Type)
            {
                case EventType.MouseMove:
                    timeline.Add(new MoveEv { SortKey = ev.Timestamp, X = ev.X ?? 0, Y = ev.Y ?? 0 });
                    break;
                case EventType.MouseMoveRelative:
                    timeline.Add(new MoveRelEv { SortKey = ev.Timestamp, Dx = ev.Dx ?? 0, Dy = ev.Dy ?? 0 });
                    break;
                case EventType.MouseDown:
                    PushHeld(openMouseHolds, ev.Button ?? "left", (ev.Timestamp, ev.X, ev.Y));
                    break;
                case EventType.MouseUp:
                    if (openMouseHolds.TryGetValue(ev.Button ?? "left", out var mstack) && mstack.Count > 0)
                    {
                        var (start, x, y) = mstack[^1];
                        mstack.RemoveAt(mstack.Count - 1);
                        timeline.Add(new MouseSpan { SortKey = start, Button = ev.Button ?? "left", End = ev.Timestamp, X = x, Y = y });
                    }
                    break;
                case EventType.MouseClick:
                    timeline.Add(new MouseSpan { SortKey = ev.Timestamp, Button = ev.Button ?? "left", End = ev.Timestamp, X = ev.X, Y = ev.Y });
                    break;
                case EventType.MouseScroll:
                    timeline.Add(new ScrollEv { SortKey = ev.Timestamp, X = ev.X, Y = ev.Y, Dy = ev.ScrollDy ?? 0 });
                    break;
                case EventType.KeyDown:
                    PushHeld(openHolds, ev.Key ?? "", ev.Timestamp);
                    break;
                case EventType.KeyUp:
                    if (openHolds.TryGetValue(ev.Key ?? "", out var kstack) && kstack.Count > 0)
                    {
                        double start = kstack[^1];
                        kstack.RemoveAt(kstack.Count - 1);
                        timeline.Add(new KeySpan { SortKey = start, Key = ev.Key ?? "", End = ev.Timestamp });
                    }
                    break;
                default:
                    
                    timeline.Add(new ControllerEv { SortKey = ev.Timestamp, Event = ev });
                    break;
            }
        }

        
        double lastTs = events.Count > 0 ? events[^1].Timestamp : 0.0;
        foreach (var (key, stack) in openHolds)
            foreach (double start in stack)
                timeline.Add(new KeySpan { SortKey = start, Key = key, End = Math.Max(lastTs, start) });
        foreach (var (button, stack) in openMouseHolds)
            foreach (var (start, x, y) in stack)
                timeline.Add(new MouseSpan { SortKey = start, Button = button, End = Math.Max(lastTs, start), X = x, Y = y });

        timeline.Sort((a, b) => a.SortKey.CompareTo(b.SortKey));
        return timeline;
    }

    private class ControllerEv : TlEvent { public RecordedEvent Event = null!; }

    private static List<string> RenderTimeline(List<TlEvent> timeline, bool collapseTyping, double minWaitThreshold)
    {
        var keyspans = timeline.OfType<KeySpan>().Cast<TlEvent>().ToList();
        var mousespans = timeline.OfType<MouseSpan>().Cast<TlEvent>().ToList();
        var allSpans = keyspans.Concat(mousespans).ToList();

        bool OverlapsAnyOther(Span span)
        {
            foreach (var other in allSpans)
            {
                if (ReferenceEquals(other, span)) continue;
                var o = (Span)other;
                if (span.SortKey < o.End && o.SortKey < span.End) return true;
            }
            return false;
        }

        
        var actions = new List<(double ts, int order, string code)>();
        int i = 0, n = timeline.Count;
        while (i < n)
        {
            var ev = timeline[i];
            switch (ev)
            {
                case MoveEv m:
                    actions.Add((m.SortKey, 0, $"move({m.X}, {m.Y})"));
                    i++;
                    continue;
                case MoveRelEv mr:
                    actions.Add((mr.SortKey, 0, $"move_relative({Math.Round(mr.Dx, 2)}, {Math.Round(mr.Dy, 2)})"));
                    i++;
                    continue;
                case MouseSpan ms:
                {
                    string xArg = ms.X?.ToString() ?? "null";
                    string yArg = ms.Y?.ToString() ?? "null";
                    if (!OverlapsAnyOther(ms))
                    {
                        int ms_ = (int)Math.Round((ms.End - ms.SortKey) * 1000);
                        actions.Add((ms.SortKey, 0, $"mouse_hold({xArg}, {yArg}, \"{ms.Button}\", {ms_})"));
                        i++;
                        continue;
                    }
                    actions.Add((ms.SortKey, 0, $"click_start({xArg}, {yArg}, \"{ms.Button}\")"));
                    actions.Add((ms.End, 1, $"click_end(\"{ms.Button}\")"));
                    i++;
                    continue;
                }
                case ScrollEv sc:
                    actions.Add((sc.SortKey, 0, sc.X is null
                        ? $"scroll({sc.Dy}, null, null)"
                        : $"scroll({sc.Dy}, {sc.X}, {sc.Y})"));
                    i++;
                    continue;
                case KeySpan ks:
                {
                    bool isLong = ks.End - ks.SortKey >= ShortHoldThreshold;
                    bool isolated = !OverlapsAnyOther(ks);
                    if (!isLong && isolated && collapseTyping && IsPrintable(ks.Key))
                    {
                        var (text, consumed) = CollapseTypingRun(timeline, i, OverlapsAnyOther);
                        if (text.Length > 0)
                        {
                            actions.Add((ks.SortKey, 0, $"type_text({VsString(text)})"));
                            i = consumed;
                            continue;
                        }
                    }
                    if (isolated)
                    {
                        int ms = (int)Math.Round((ks.End - ks.SortKey) * 1000);
                        actions.Add((ks.SortKey, 0, $"key_hold(\"{EscapeKey(ks.Key)}\", {ms})"));
                        i++;
                        continue;
                    }
                    actions.Add((ks.SortKey, 0, $"hold_start(\"{EscapeKey(ks.Key)}\")"));
                    actions.Add((ks.End, 1, $"hold_end(\"{EscapeKey(ks.Key)}\")"));
                    i++;
                    continue;
                }
                case ControllerEv ce:
                    actions.Add((ce.SortKey, 0, RenderController(ce.Event)));
                    i++;
                    continue;
                default:
                    i++;
                    continue;
            }
        }

        actions.Sort((a, b) =>
        {
            int c = a.ts.CompareTo(b.ts);
            return c != 0 ? c : a.order.CompareTo(b.order);
        });

        var lines = new List<string>();
        double lastTime = 0.0;
        foreach (var (ts, _, code) in actions)
        {
            double gap = ts - lastTime;
            if (gap >= minWaitThreshold)
                lines.Add($"wait({Math.Round(gap, 3)})");
            lastTime = ts;
            lines.Add(code);
        }
        return lines;
    }

    private static string RenderController(RecordedEvent ev) => ev.Type switch
    {
        EventType.ControllerButtonPress => $"controller_press({ev.ControllerId ?? 0}, \"{ev.Button}\")",
        EventType.ControllerButtonRelease => $"controller_release({ev.ControllerId ?? 0}, \"{ev.Button}\")",
        EventType.ControllerStickMove => $"controller_stick({ev.ControllerId ?? 0}, \"{ev.Button}\", {Math.Round(ev.StickX ?? 0, 3)}, {Math.Round(ev.StickY ?? 0, 3)})",
        EventType.ControllerTriggerMove => $"controller_trigger({ev.ControllerId ?? 0}, \"{ev.Button}\", {Math.Round(ev.TriggerValue ?? 0, 3)})",
        EventType.ControllerDPadMove => $"controller_dpad({ev.ControllerId ?? 0}, \"{ev.DPadDirection}\")",
        _ => $"# unsupported event {ev.Type}",
    };

    private static bool IsPrintable(string key)
        => key.Length == 1 && (key[0] == ' ' || (!char.IsControl(key[0]) && !char.IsWhiteSpace(key[0])));

    private static (string text, int consumed) CollapseTypingRun(List<TlEvent> timeline, int start, Func<Span, bool> overlapsAnyOther)
    {
        var chars = new StringBuilder();
        int i = start, n = timeline.Count;
        double lastTs = timeline[start].SortKey;
        while (i < n)
        {
            if (timeline[i] is not KeySpan ks || !IsPrintable(ks.Key) || ks.End - ks.SortKey >= ShortHoldThreshold)
                break;
            if (overlapsAnyOther(ks)) break;
            if (chars.Length > 0 && ks.SortKey - lastTs > TypingGapThreshold) break;
            chars.Append(ks.Key);
            lastTs = ks.End;
            i++;
        }
        return (chars.ToString(), i);
    }

    private static string EscapeKey(string key) => key.Replace("\"", "\\\"");

    private static string VsString(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n") + "\"";
}
